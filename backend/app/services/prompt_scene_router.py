def infer_scene_from_signals(text: str, bert: BertResult | None) -> tuple[str, dict[str, int]]:
    """
    返回 (场景, 各场景命中次数)。
    general 不参与关键词加分，仅作为无命中时的默认。
    """
    parts: list[str] = [text or ""]
    if bert is not None:
        parts.append(" ".join(bert.predicted_label_names or []))
        parts.append(bert.prediction_summary_zh or "")
    hay = " ".join(parts).lower()

    scores: dict[str, int] = {s: 0 for s in _SCENE_PRIORITY}
    for scene, kws in _SCENE_KEYWORDS.items():
        if scene == "general":
            continue
        n = 0
        for kw in kws:
            if kw.lower() in hay:
                n += 1
        scores[scene] = n

    best = max((scores[s] for s in _SCENE_PRIORITY if s != "general"), default=0)
    if best <= 0:
        scores["general"] = 1
        return "general", scores

    winners = [s for s in _SCENE_PRIORITY if s != "general" and scores[s] == best]
    if len(winners) == 1:
        return winners[0], scores
    for s in _SCENE_PRIORITY:
        if s in winners:
            return s, scores
    return "general", scores


def truthy_auto_prompt(v: Any, *, default: bool = True) -> bool:
    """解析管理端 auto_prompt_scene（bool / 0|1 / 字符串）。"""
    if v is None:
        return default
    if isinstance(v, bool):
        return v
    if isinstance(v, (int, float)):
        return bool(v)
    s = str(v).strip().lower()
    if s in {"0", "false", "no", "off"}:
        return False
    if s in {"1", "true", "yes", "on"}:
        return True
    return default
